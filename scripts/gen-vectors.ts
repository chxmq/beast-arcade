// Generates contracts/tests/test_vectors.cairo from the TypeScript reference sim (SPEC v2).
// Every vector replays a strike log in Cairo and must match the TS RunResult field for field.
// npx tsx scripts/gen-vectors.ts
import { writeFileSync } from 'node:fs';
import { encodeStrike, type Strike } from '../src/sim/encode.ts';
import { positionAt } from '../src/sim/motion.ts';
import { Run, replay, type RunResult } from '../src/sim/replay.ts';
import type { SimRosterEntry } from '../src/sim/schedule.ts';
import { GAP_HIT, GAP_MISS, MAX_STRIKES, REACTION_TICKS, type BeastType } from '../src/sim/spec.ts';

function mulberry(a: number) {
  return () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}

function randomRoster(rng: () => number, n: number): SimRosterEntry[] {
  const out: SimRosterEntry[] = [];
  for (let k = 0; k < n; k++) {
    let occ = 0n;
    const density = 0.4 + rng() * 0.6;
    for (let b = 0; b < 64; b++) if (rng() < density) occ |= 1n << BigInt(b);
    if (occ === 0n) occ = 1n << 27n;
    out.push({
      type: Math.floor(rng() * 3) as BeastType,
      tier: 1 + Math.floor(rng() * 5),
      health: rng() < 0.75 ? 100 : 40 + Math.floor(rng() * 200),
      aggr: rng() < 0.6 ? 0 : Math.floor(rng() * 4),
      w: 16 + Math.floor(rng() * 49),
      h: 16 + Math.floor(rng() * 41),
      occ,
    });
  }
  return out;
}

type Style = 'oracle' | 'sloppy' | 'spam' | 'idle' | 'edges' | 'overkill' | 'max';

function strikesFor(style: Style, seed: bigint, roster: SimRosterEntry[], nF: number, rng: () => number): number[] {
  if (style === 'idle') return [];
  const run = new Run(seed, roster, nF);
  const out: number[] = [];
  const push = (st: Strike) => { run.strike(st); out.push(encodeStrike(st)); };
  for (let tick = 0; tick <= run.endTick + 40 && tick < 3990 && out.length < MAX_STRIKES; tick++) {
    run.advanceTo(tick);
    if (!run.canStrike(tick)) continue;
    if (style === 'spam' || style === 'max') {
      if (style === 'spam' && rng() < 0.7) continue;
      push({ tick, x: Math.floor(rng() * 256), y: Math.floor(rng() * 144), type: 0 });
      continue;
    }
    if (run.dead) {
      // keep validating strikes after death sometimes
      if (rng() < 0.02) push({ tick, x: Math.floor(rng() * 256), y: Math.floor(rng() * 144), type: 0 });
      continue;
    }
    let target = -1;
    for (let i = 0; i < run.spawns.length; i++) {
      const s = run.spawns[i];
      if (style === 'edges') {
        if ((run.alive[i] || run.killed[i]) && [s.spawnTick + REACTION_TICKS - 1, s.spawnTick + REACTION_TICKS, s.escapeTick - 1, s.escapeTick].includes(tick)) { target = i; break; }
      } else if (style === 'overkill') {
        // click killed Beasts again while they are still in their window
        if ((run.isTargetable(i, tick) || (run.killed[i] && run.isVisibleWindow(i, tick))) && rng() < 0.5) { target = i; break; }
      } else if (run.isTargetable(i, tick) && tick >= s.spawnTick + REACTION_TICKS + Math.floor(rng() * (style === 'oracle' ? 10 : 60))) { target = i; break; }
    }
    if (target < 0) continue;
    const s = run.spawns[target];
    const { px, py } = positionAt(s, tick);
    let x = px + Math.floor(rng() * s.entry.w);
    let y = py + Math.floor(rng() * s.entry.h);
    if (style === 'oracle') { x = px + (s.entry.w >> 1); y = py + (s.entry.h >> 1); }
    if (style === 'sloppy' && rng() < 0.35) { x += rng() < 0.5 ? -12 : 12; y += rng() < 0.5 ? -6 : 6; }
    push({ tick, x: Math.max(0, Math.min(255, x)), y: Math.max(0, Math.min(143, y)), type: 0 });
  }
  return out;
}

interface Vector { name: string; seed: bigint; roster: SimRosterEntry[]; nF: number; strikes: number[]; result: RunResult }

const rng = mulberry(20261117);
const styles: Style[] = ['oracle', 'sloppy', 'spam', 'idle', 'edges', 'overkill', 'max'];
const vectors: Vector[] = [];
for (let k = 0; k < 63; k++) {
  const style = styles[k % styles.length];
  const n = 1 + Math.floor(rng() * 14);
  const nF = k % 9 === 0 ? 0 : k % 11 === 0 ? n : Math.min(n, 1 + Math.floor(rng() * n));
  const roster = randomRoster(rng, n);
  const seed = BigInt('0x' + Array.from({ length: 62 }, () => Math.floor(rng() * 16).toString(16)).join('')) % (2n ** 251n);
  const strikes = strikesFor(style, seed, roster, nF, rng);
  const result = replay(seed, roster, nF, strikes);
  vectors.push({ name: `${style}_${k}`, seed, roster, nF, strikes, result });
}

const hex = (v: bigint) => '0x' + v.toString(16);
let src = `// GENERATED by scripts/gen-vectors.ts from the TypeScript reference sim (src/sim). Do not edit.
// SPEC.md v3.0 parity vectors: Cairo replay must match TS field for field.
use static_game::sim::{RosterEntry, replay};

fn r(beast_type: u8, tier: u8, health: u16, aggr: u8, w: u8, h: u8, occ: u64) -> RosterEntry {
    RosterEntry { beast_type, tier, health, aggr, w, h, occ }
}
`;
for (const v of vectors) {
  const ros = v.roster.map((e) => `r(${e.type}, ${e.tier}, ${e.health}, ${e.aggr}, ${e.w}, ${e.h}, ${hex(e.occ)})`).join(', ');
  const R = v.result;
  src += `
#[test]
fn vector_${v.name}() {
    let roster = array![${ros}];
    let strikes: Array<u32> = array![${v.strikes.join(', ')}];
    let res = replay(${hex(v.seed)}, roster.span(), ${v.nF}, strikes.span());
    assert_eq!(res.score, ${R.score});
    assert_eq!(res.kills, ${R.kills});
    assert_eq!(res.lives, ${R.lives});
    assert_eq!(res.dead, ${R.dead});
    assert_eq!(res.death_tick, ${R.deathTick});
    assert_eq!(res.killer, ${R.killer});
    assert_eq!(res.killer_roster, ${R.killerRoster});
    assert_eq!(res.best_combo, ${R.bestCombo});
    assert_eq!(res.caught_mask, ${hex(R.caughtMask)});
    assert_eq!(res.shiny_mask, ${hex(R.shinyMask)});
    assert_eq!(res.digest, ${hex(R.digest)});
}
`;
}
writeFileSync(new URL('../contracts/tests/test_vectors.cairo', import.meta.url), src);
writeFileSync(new URL('../scripts/out/vectors.json', import.meta.url), JSON.stringify(vectors, (_k, x) => (typeof x === 'bigint' ? hex(x) : x), 1));

// coverage summary
let jams = 0, overkills = 0, jamDeaths = 0, escDeaths = 0, alive = 0;
for (const v of vectors) {
  const run = new Run(v.seed, v.roster, v.nF);
  for (const s of v.strikes) {
    const ev = run.strike({ tick: Math.floor(s / 262144), x: Math.floor(s / 1024) % 256, y: Math.floor(s / 4) % 256, type: 0 });
    if (ev && ev.kind === 'strike' && ev.outcome === 'overkill') overkills++;
  }
  run.finish();
  jams += run.events.filter((e) => e.kind === 'jam').length;
  if (!v.result.dead) alive++;
  else if (v.result.killer === 255) jamDeaths++;
  else escDeaths++;
}
console.log(`wrote ${vectors.length} vectors (GAP_HIT ${GAP_HIT}, GAP_MISS ${GAP_MISS})`, { alive, escDeaths, jamDeaths, jams, overkills, maxStrikes: Math.max(...vectors.map((v) => v.strikes.length)) });
