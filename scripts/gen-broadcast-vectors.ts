// Generates contracts/tests/test_broadcast_ts.cairo: the Broadcast server's TypeScript hashing
// (seeds, Merkle tree and proofs, tape index, message hash, Stark signature, raw submit_broadcast
// calldata) checked against the Cairo contract, including a full submission through the raw
// calldata the relayer sends.
// npx tsx scripts/gen-broadcast-vectors.ts && (cd contracts && snforge test test_broadcast_ts)
import { writeFileSync } from 'node:fs';
import { getStarkKey, sign } from '@scure/starknet';
import { encodeShortString, hex, leafHash, messageHash, tapeIndex } from '../src/broadcast/hashes.ts';
import { buildTree, proofFor } from '../src/broadcast/merkle.ts';
import { encodeStrike } from '../src/sim/encode.ts';
import { occHit, positionAt } from '../src/sim/motion.ts';
import { Run, replay } from '../src/sim/replay.ts';
import { aggrFromKills, type SimRosterEntry } from '../src/sim/schedule.ts';
import { REACTION_TICKS } from '../src/sim/spec.ts';
import { submitCalldata } from '../server/chain.ts';
import { seedFor } from '../server/seeds.ts';

const SECRET = 0x5354415449432d54455354n; // 'STATIC-TEST'
const DAY = 20409;
const PRIV = '0x2dccce1da22003777062ee0870e9881b63fb7d9ed7a8b2e3b0e7f0ff5d7b9b1';

const lines: string[] = [];
const out = (s = '') => lines.push(s);
const felts = (xs: bigint[]) => xs.map(hex).join(', ');

out('// GENERATED by scripts/gen-broadcast-vectors.ts from the TypeScript Broadcast server code. Do not edit.');
out('// The relayer\'s hashing (seeds, Merkle proofs, tape index, message, signature, raw calldata) must be');
out('// accepted by the contract exactly as the TS computes it.');
out('use core::poseidon::poseidon_hash_span;');
out('use openzeppelin_merkle_tree::merkle_proof::verify_poseidon;');
out('use snforge_std::{');
out('    ContractClassTrait, DeclareResultTrait, declare, start_cheat_block_timestamp_global,');
out('    start_cheat_caller_address, stop_cheat_caller_address,');
out('};');
out('use starknet::ContractAddress;');
out('use starknet::syscalls::call_contract_syscall;');
out('use static_game::interfaces::{IStaticGameDispatcher, IStaticGameDispatcherTrait, RosterInput};');
out('use static_game::static_game::StaticGame::{leaf_of, message_of, tape_index_of};');
out('use crate::mocks::{IMockRegistryDispatcher, IMockRegistryDispatcherTrait};');
out();
out(`const SECRET: felt252 = ${hex(SECRET)};`);
out(`const DAY: felt252 = ${DAY};`);
out();

// ---------------------------------------------------------------- Merkle trees (4 and 5 leaves)
const seeds = Array.from({ length: 5 }, (_, k) => seedFor(SECRET, DAY, k));
for (const n of [4, 5]) {
  const tree = buildTree(seeds.slice(0, n).map((s, k) => leafHash(k, s)));
  out('#[test]');
  out(`fn ts_merkle_${n}_leaves() {`);
  out(`    let root = ${hex(tree.root)};`);
  for (let k = 0; k < n; k++) {
    out(`    let seed = ${hex(seeds[k])};`);
    out(`    assert_eq!(poseidon_hash_span(array![SECRET, DAY, ${k}].span()), seed);`);
    out(`    assert!(verify_poseidon(array![${felts(proofFor(tree, k))}].span(), root, leaf_of(${k}, seed)));`);
  }
  out('    // A proof for the wrong leaf index fails.');
  out(`    assert!(!verify_poseidon(array![${felts(proofFor(tree, 0))}].span(), root, leaf_of(1, ${hex(seeds[1])})));`);
  out('}');
  out();
}

// ---------------------------------------------------------------- message hash and tape index
const pub = BigInt(getStarkKey(PRIV));
const msgStrikes = [0, encodeStrike({ tick: 4, x: 10, y: 20, type: 1 }), 3999 * 262144 + 255 * 1024 + 143 * 4 + 2];
out('#[test]');
out('fn ts_message_hash_and_tape_index() {');
out(`    assert_eq!('ACE42', ${hex(encodeShortString('ACE42'))});`);
out(`    assert_eq!(message_of(7, 1234, 0x2a, 'ACE42', array![${msgStrikes.join(', ')}].span()), ${hex(messageHash(7, 1234, 0x2an, encodeShortString('ACE42'), msgStrikes))});`);
out(`    assert_eq!(message_of(1, 0, 1, 'A', array![].span()), ${hex(messageHash(1, 0, 1n, encodeShortString('A'), []))});`);
out(`    assert_eq!(tape_index_of(${hex(pub)}, 0x2a, 4096), ${tapeIndex(pub, 0x2an, 4096)});`);
out(`    assert_eq!(tape_index_of(${hex(pub)}, 0x2a, 5), ${tapeIndex(pub, 0x2an, 5)});`);
out('}');
out();

// ---------------------------------------------------------------- full submission via raw calldata
// Roster of contracts/tests/test_game.cairo (registry type/tier, health, aggr from base_kills).
const inputs = [
  { species: 10011, type: 0, tier: 3, health: 0, w: 48, h: 40, occ: 0x3c7effffffff7e3cn, base: 0 },
  { species: 10012, type: 1, tier: 2, health: 120, w: 40, h: 32, occ: 0xffffffffffffffffn, base: 1 },
  { species: 10013, type: 2, tier: 4, health: 100, w: 56, h: 48, occ: 0x7e7e7e7e7e7e7e7en, base: 7 },
  { species: 1, type: 0, tier: 1, health: 80, w: 32, h: 32, occ: 0x00ffff00ffff00ffn, base: 0 },
  { species: 2, type: 1, tier: 5, health: 100, w: 64, h: 56, occ: 0xffffffffffffffffn, base: 3 },
  { species: 3, type: 2, tier: 3, health: 150, w: 24, h: 24, occ: 0x8142241818244281n, base: 0 },
];
const N_FEATURED = 3;
const roster: SimRosterEntry[] = inputs.map((e) => ({
  type: e.type as 0 | 1 | 2, tier: e.tier, health: e.health || 100, aggr: aggrFromKills(e.base), w: e.w, h: e.h, occ: e.occ,
}));
const n = 4;
const tree = buildTree(seeds.slice(0, n).map((s, k) => leafHash(k, s)));
const nonce = 1n;
const k = tapeIndex(pub, nonce, n);
const seed = seeds[k];
// v3: clicks on the first Beasts (centre of their first occupied cell) at their reaction tick and
// a few ticks later (kills, combo, overkill), skipping ticks the gap rule forbids, plus a miss.
const strikes: number[] = [];
const sim = new Run(seed, roster, N_FEATURED);
for (const s of sim.spawns.slice(0, 6)) {
  for (const dt of [REACTION_TICKS, REACTION_TICKS + 6, REACTION_TICKS + 24, REACTION_TICKS + 42]) {
    const tick = s.spawnTick + dt;
    if (!sim.canStrike(tick)) continue;
    const { px, py } = positionAt(s, tick);
    let cell = 0;
    while (!((s.entry.occ >> BigInt(cell)) & 1n)) cell++;
    const lx = Math.floor((((cell % 8) + 0.5) * s.entry.w) / 8);
    const ly = Math.floor(((Math.floor(cell / 8) + 0.5) * s.entry.h) / 8);
    if (!occHit(s.entry.occ, s.entry.w, s.entry.h, lx, ly)) throw new Error('aim');
    const st = { tick, x: Math.min(255, px + lx), y: Math.min(143, py + ly), type: 0 as const };
    sim.strike(st);
    strikes.push(encodeStrike(st));
  }
}
strikes.push(encodeStrike({ tick: 3000, x: 0, y: 0, type: 0 })); // a miss (nothing there at tick 3000 is not guaranteed; the replay decides)
const callsign = encodeShortString('TSRELAY');
const msg = messageHash(1, k, nonce, callsign, strikes);
const sig = sign(hex(msg), PRIV);
const calldata = submitCalldata({ rootId: 1, k, nonce, seed, proof: proofFor(tree, k), pub, callsign, strikes, r: sig.r, s: sig.s });
const res = replay(seed, roster, N_FEATURED, strikes);

out('fn relayer() -> ContractAddress {');
out("    'relayer'.try_into().unwrap()");
out('}');
out();
out('fn owner() -> ContractAddress {');
out("    'owner'.try_into().unwrap()");
out('}');
out();
out('#[test]');
out('fn ts_submit_broadcast_raw_calldata() {');
out('    let t0: u64 = 1763337600 + 3600;');
out('    start_cheat_block_timestamp_global(t0);');
out('    let (reg_addr, _) = declare("MockRegistry").unwrap().contract_class().deploy(@array![]).unwrap();');
out('    let (nft_addr, _) = declare("MockBeasts").unwrap().contract_class().deploy(@array![reg_addr.into()]).unwrap();');
out('    let (addr, _) = declare("StaticGame").unwrap().contract_class()');
out('        .deploy(@array![owner().into(), reg_addr.into(), nft_addr.into()]).unwrap();');
out('    let registry = IMockRegistryDispatcher { contract_address: reg_addr };');
for (const e of inputs) out(`    registry.set_definition(${e.species}, ${e.type}, ${e.tier});`);
out('    let game = IStaticGameDispatcher { contract_address: addr };');
out('    start_cheat_caller_address(addr, owner());');
out('    game.set_roster(array![');
for (const e of inputs) {
  out(`        RosterInput { species_id: ${e.species}, health: ${e.health}, w: ${e.w}, h: ${e.h}, occ: ${hex(e.occ)}, kill_token: 0, base_kills: ${e.base} },`);
}
out(`    ], ${N_FEATURED});`);
out('    game.set_relayer(relayer(), true);');
out('    start_cheat_caller_address(addr, relayer());');
out(`    let root_id = game.post_tape_root(${hex(tree.root)}, ${n}, t0 + 86400);`);
out('    assert_eq!(root_id, 1);');
out(`    assert_eq!(game.tape_index(1, ${hex(pub)}, 1), ${k});`);
out(`    // Exactly the calldata server/chain.ts submitCalldata() builds for the relayer.`);
out(`    let calldata = array![${felts(calldata)}];`);
out("    let ret = call_contract_syscall(addr, selector!(\"submit_broadcast\"), calldata.span()).unwrap();");
out('    assert_eq!(*ret.at(0), 1); // run_id');
out('    stop_cheat_caller_address(addr);');
out('    let run = game.get_run(1);');
out(`    assert_eq!(run.player_pub, ${hex(pub)});`);
out(`    assert_eq!(run.callsign, 'TSRELAY');`);
out(`    assert_eq!(run.k, ${k});`);
out(`    assert_eq!(run.seed, ${hex(seed)});`);
out(`    assert_eq!(run.score, ${res.score});`);
out(`    assert_eq!(run.kills, ${res.kills});`);
out(`    assert_eq!(run.lives, ${res.lives});`);
out(`    assert_eq!(run.best_combo, ${res.bestCombo});`);
out(`    assert_eq!(run.caught_mask, ${hex(res.caughtMask)});`);
out(`    assert_eq!(run.dead, ${res.dead});`);
out(`    assert_eq!(run.digest, ${hex(res.digest)});`);
out(`    assert!(game.is_tape_used(1, ${k}));`);
out('    // Bestiary: the TS sim\'s masks and kill count land in the player\'s dex.');
out(`    assert_eq!(game.get_dex(${hex(pub)}), (${hex(res.caughtMask)}, ${hex(res.shinyMask)}, ${res.kills}));`);
out('}');

writeFileSync('contracts/tests/test_broadcast_ts.cairo', lines.join('\n') + '\n');
console.log(`wrote contracts/tests/test_broadcast_ts.cairo (k=${k}, ${strikes.length} strikes, score ${res.score}, kills ${res.kills})`);
