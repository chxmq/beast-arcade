// Bundles the Broadcast API (server/handlers.ts) into one self-contained ESM file per Vercel
// function under api/. Each exports Web handlers (`export async function GET(request)`), which
// Vercel's Node.js runtime serves directly. roster.json is inlined by the bundler.
// The api/ files are GENERATED: edit server/ and run `npm run build:api` (also part of `npm run build`).
import { build } from 'esbuild';

const ROUTES: Record<string, { GET?: string; POST?: string }> = {
  'broadcast/status': { GET: 'status' },
  'broadcast/start': { POST: 'start' },
  'broadcast/seg': { GET: 'seg' },
  'broadcast/submit': { POST: 'submit' },
  'cron/post-root': { GET: 'postRoot', POST: 'postRoot' },
};

for (const [route, methods] of Object.entries(ROUTES)) {
  const exports = Object.entries(methods).map(([method, fn]) => `${fn} as ${method}`).join(', ');
  await build({
    stdin: { contents: `export { ${exports} } from './server/handlers.ts';`, resolveDir: process.cwd(), sourcefile: `${route}.ts`, loader: 'ts' },
    outfile: `api/${route}.js`,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    legalComments: 'none',
    minify: true,
    logLevel: 'warning',
    banner: {
      js: [
        '// GENERATED by scripts/build-api.ts from server/handlers.ts. Do not edit; run `npm run build:api`.',
        "import { createRequire as __createRequire } from 'node:module';",
        'const require = __createRequire(import.meta.url);',
      ].join('\n'),
    },
  });
  console.log(`api/${route}.js  ${Object.keys(methods).join(' ')}`);
}
